function [ data,np,nodes,Nele ] = shujuzhenhe_3D( x3,y3,z3,p3,h3,hr3,vx,vy,vz,han,lie,zn)
%% ????????
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%??????X????Y????????????
Nnx=lie;
Nny=han;
Nnz=zn; %????????????????????????
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
Nex=Nnx-1;      %??????????X????????????????
Ney=Nny-1;      %??????????Y????????????????
Nez=Nnz-1;      %??????????Z????????????????
Nelayer=Nex*Ney;  %??????????
Nnlayer=Nnx*Nny;  %??????????
Nele=Nelayer*Nez; %??????????
Nn=Nnlayer*Nnz;   %??????????

elements = [1 : Nele]';
np = zeros(Nele,8);%????????????????np = zeros(Nele,8);

remainderLe = mod(elements,Nelayer);        %??????????????????????????????
remainderLe(find(remainderLe==0)) = Nelayer;%????????????????????????????????
remainderXe = mod(remainderLe,Nex);
remainderXe(find(remainderXe==0)) = Nex;    %??????????????????x??y????

np(:,1) = (ceil(elements/Nelayer)-1) * Nnlayer + (ceil(remainderLe/Nex)-1) * Nnx + remainderXe;
np(:,2) = np(:,1) + 1;
np(:,3) = np(:,2) + Nnx;
np(:,4) = np(:,1) + Nnx;
np(:,5:8) = np(:,1:4) + Nnlayer;          %??????????????????????????????
%% ??????tecplot??????????
data=zeros(han*lie*zn,9);
lm=1;
for k = 1:zn
    for i=1:han
        for j = 1:lie
            if i>j
                data(lm,1)=x3(i,j,k);
                data(lm,2)=y3(i,j,k);
                data(lm,3)=z3(i,j,k);
                data(lm,4)=p3(i,j,k);
                data(lm,5)=h3(i,j,k);
                data(lm,6)=hr3(i,j,k);
                data(lm,7)=vx(i,j,k);
                data(lm,8)=vy(i,j,k);
                data(lm,9)=vz(i,j,k);
            else
                data(lm,1)=x3(i,i,k);
                data(lm,2)=y3(i,i,k);
                data(lm,3)=z3(i,i,k);
                data(lm,4)=p3(i,i,k);
                data(lm,5)=h3(i,i,k);
                data(lm,6)=hr3(i,i,k);
                data(lm,7)=vx(i,i,k);
                data(lm,8)=vy(i,i,k);
                data(lm,9)=vz(i,i,k);
            end
 lm=lm+1;
        end    
    end
end
nodes=han*lie*zn;
end
